test('a real training batch saves Q updates and page eight compares two read-only frozen policies',async({page})=>{
  await page.goto('/#training');
  await page.evaluate(()=>localStorage.setItem('robotcoach:q:v1','{"updates":55,"q":{"legacy":[1,2,3]}}'));
  const f=frame(page),legacy=await stored(page,'robotcoach:q:v1');
  await expect(f.locator('#updates')).toHaveText('0');
  await f.locator('#play').click();
  await expect(f.locator('#attempts')).toHaveText('300',{timeout:35000});
  await expect(f.locator('#feedback')).toContainText('本批训练结束');
  const trained=await stored(page);
  const model=JSON.parse(trained);
  expect(model.attempts).toBe(300);
  expect(model.updates).toBeGreaterThan(1000);
  expect(model.audit).toHaveLength(12);
  expect(Object.values(model.q).some(q=>q.some(x=>x!==0))).toBe(true);
  await page.screenshot({path:join(evidence,'chapter2-desktop-training.png'),fullPage:true});
  await page.reload();
  await expect(f.locator('#updates')).toHaveText(String(model.updates));
  await f.getByText('奖励规则与真实 Q 更新',{exact:true}).click();
  await expect(f.locator('#auditRows tr')).toHaveCount(12);
  await expect(f.locator('#rewardBreakdown')).toContainText('上轮奖励构成');
  await f.locator('#showcaseLink').click();
  await expect(page).toHaveURL(/#showcase$/);
  await f.locator('#compare').click();
  await expect(f.locator('#comparison')).toBeVisible();
  await expect(f.locator('#comparisonStatus')).toContainText('至少一项成绩提高');
  const {report}=JSON.parse(await stored(page,COMPARISON_KEY));
  expect(report.before.runs.map(x=>x.seed)).toEqual(report.after.runs.map(x=>x.seed));
  expect(report.seeds).toEqual(Array.from({length:20},(_,i)=>9001+i));
  expect(report.before.successes).toBe(0);
  const pairs=f.locator('#trackPairs button');
  await expect(pairs).toHaveCount(report.seeds.length);
  expect(await f.locator('#trackPairs .cleared').count()).toBe(report.before.successes+report.after.successes);
  await pairs.last().click();
  await expect(f.locator('#pairReading')).toContainText(`种子 ${report.seeds.at(-1)}`);
  await expect(f.locator('#beforeTotal')).toHaveText(`${report.before.successes} / 20`);
  await expect(f.locator('#afterTotal')).toHaveText(`${report.after.successes} / 20`);
  await f.getByRole('button',{name:'看跑道'}).click();
  await expect(f.locator('#motionCanvas')).toBeVisible();
  await f.getByRole('button',{name:'看同场对照'}).click();
  await expect(f.locator('#motionCanvas')).toBeHidden();
  expect(report.after.meanPassed).toBeGreaterThan(report.before.meanPassed);
  expect(await stored(page)).toBe(trained);
  await page.screenshot({path:join(evidence,'chapter2-desktop-frozen.png'),fullPage:true});
  await page.reload();
  await expect(f.locator('#comparisonRows tr')).toHaveCount(3);
  await f.getByText('逐轮成绩与失败原因',{exact:true}).click();
  await expect(f.locator('#rounds li')).toHaveCount(20);
  await f.getByText('逐轮成绩与失败原因',{exact:true}).click();
  await page.clock.install();
  await f.locator('#policy').selectOption('rule');
  await expect(f.locator('#roles')).toContainText('规则参考决定越障动作');
  await f.locator('#play').click();
  await page.clock.runFor(8000);
  await expect(f.locator('#feedback')).toHaveAttribute('data-outcome','passed');
  await expect(f.locator('#passed')).toHaveText('越障 3 个');
  expect(await stored(page)).toBe(trained);
  expect(await stored(page,'robotcoach:q:v1')).toBe(legacy);
});

test('training pauses on hide, flushes on navigation and respects a reset in another tab',async({page,context})=>{
  await page.goto('/#training');const f=frame(page);
  await f.locator('#play').click();
  const updates=()=>f.locator('#updates').textContent().then(Number);
  await expect.poll(updates).toBeGreaterThan(3);
  await page.evaluate(()=>document.getElementById('experiment').contentWindow.postMessage(
    {type:'robotcoach:visibility',hidden:true},location.origin));
  await expect(f.locator('#play')).toHaveText('继续训练');
  const paused=await updates();
  await page.waitForTimeout(300);
  expect(await updates()).toBe(paused);
  await page.evaluate(()=>document.getElementById('experiment').contentWindow.postMessage(
    {type:'robotcoach:visibility',hidden:false},location.origin));
  await f.locator('#play').click();
  await expect.poll(updates).toBeGreaterThan(paused);
  const shown=await updates();
  await page.getByRole('button',{name:'三 · AI闭环'}).click();
  const checkpoint=await stored(page);
  expect(JSON.parse(checkpoint).updates).toBeGreaterThanOrEqual(shown);
  await page.waitForTimeout(300);
  expect(await stored(page)).toBe(checkpoint);
  await page.goto('/#training');
  await expect(f.locator('#updates')).toHaveText(String(JSON.parse(checkpoint).updates));
  await f.locator('#play').click();
  const other=await context.newPage();
  await other.goto('/#training');
  await frame(other).getByText('奖励规则与真实 Q 更新',{exact:true}).click();
  await frame(other).locator('#reset').click();
  await expect(f.locator('#updates')).toHaveText('0');
  await expect(f.locator('#play')).toHaveText('开始训练');
  expect(JSON.parse(await stored(page)).q).toEqual({});
});

test('320px touch controls and an untrained comparison remain usable',async({browser,baseURL})=>{
  const context=await browser.newContext({baseURL,viewport:{width:320,height:740},hasTouch:true,isMobile:true});
  const page=await context.newPage();const errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto('/#manual');const f=frame(page);
  await f.locator('#play').tap();
  await f.locator('#jump').tap();
  await expect(f.locator('#motionState')).toHaveText('腾空');
  await f.locator('#duck').tap();
  await expect(f.locator('#duck')).toHaveAttribute('aria-pressed','true');
  await page.goto('/#showcase');
  await f.locator('body').evaluate(()=>{
    document.getElementById('compare').click();
    document.getElementById('cancelCompare').click();
  });
  await expect(f.locator('#comparisonStatus')).toHaveText('已取消比较。');
  expect(await stored(page,COMPARISON_KEY)).toBeNull();
  await f.locator('#compare').tap();
  await expect(f.locator('#comparisonStatus')).toContainText('本次未测到成绩提高');
  expect(await stored(page)).toBeNull();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  expect(await f.locator('body').evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.screenshot({path:join(evidence,'chapter2-narrow-frozen.png'),fullPage:true});
  expect(errors).toEqual([]);
  await context.close();
});
