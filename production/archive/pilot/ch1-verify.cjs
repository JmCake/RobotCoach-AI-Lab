const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
const dest=path.resolve(__dirname,'../../chapter1-classroom/docs/第一关样片');
fs.mkdirSync(dest,{recursive:true});
const origin='http://127.0.0.1:24861/rescue.html';
(async()=>{
  const browser=await chromium.launch({channel:'msedge',headless:true});
  try{
    const page=await browser.newPage({viewport:{width:1440,height:900},deviceScaleFactor:1});
    const warnings=[];page.on('pageerror',e=>warnings.push(e.message));page.on('response',res=>{if(res.status()>=400)warnings.push(res.status()+' '+res.url());});
    const button=n=>page.getByRole('button',{name:n,exact:true});
    const click=n=>button(n).click();
    const wait=async p=>{await page.waitForSelector('body[data-state="'+p+'"]',{timeout:26000});};
    const screenshot=async name=>{await page.evaluate(()=>document.fonts.ready);await page.screenshot({path:path.join(dest,name+'.jpg'),quality:88});};
    const state=()=>page.evaluate(()=>JSON.parse(sessionStorage.getItem('robotcoach:rescue-pilot:v1')));
    await page.goto(origin);await wait('intro');await screenshot('01-比赛开始');await click('▶　播放比赛');
    await page.waitForFunction(()=>document.querySelector('video').currentTime>1.8);
    await click('Ⅱ　暂停镜头');let t=await page.locator('video').evaluate(v=>v.currentTime);await page.waitForTimeout(400);
    assert.equal(await page.locator('video').evaluate(v=>v.currentTime),t);
    await click('调查记录');await click('关闭');assert(await page.locator('video').evaluate(v=>v.paused));
    await click('▶　继续镜头');await wait('prediction');assert(await page.locator('video').evaluate(v=>v.paused));
    assert(await button('揭晓现场　→').isDisabled());await click('可能会摔');await screenshot('02-预测定格');await click('揭晓现场　→');
    await wait('incident');await wait('question');await screenshot('03-事故现场');
    await click('翻开现场线索　→');await wait('evidence');const go=button('带着猜想去改装　→');assert(await go.isDisabled());
    for(const c of ['眼睛','身体','脚底'])await click('观察'+c);
    await page.locator('textarea').fill('我怀疑脚滑。把碎石拿掉，再检查脚底还有没有滑移。');
    await screenshot('04-三格线索');await go.click();await wait('bench');
    await click('足底力觉');await screenshot('05-改装选择');await click('用这套装备试跑　→');await wait('running');
    await page.waitForFunction(()=>parseFloat(document.getElementById('meters')?.textContent)>1);
    await click('Ⅱ　暂停试跑');const d=await page.locator('#meters').innerText();await page.waitForTimeout(350);assert.equal(await page.locator('#meters').innerText(),d);
    await click('▶　继续试跑');await wait('result');
    let record=(await state()).history.at(-1);assert(!record.success&&record.slip===0);
    assert(!await button('播放成功过弯　→').count());await screenshot('06-真实失败');
    await click('调整装备再试　→');await click('足底力觉');await click('姿态 IMU');await click('仅测量');await click('用这套装备试跑　→');await wait('result');
    record=(await state()).history.at(-1);assert(!record.success&&!record.corrected&&record.tilt>40);
    await page.reload();await wait('result');await click('调整装备再试　→');await click('接入控制器');await click('用这套装备试跑　→');await wait('result');
    record=(await state()).history.at(-1);assert(record.success&&record.corrected&&record.distance>=40);await screenshot('07-实际完赛');
    await click('播放成功过弯　→');await wait('victory');await page.waitForFunction(()=>document.querySelector('video').currentTime>1.4);
    await screenshot('08-成功过弯');await wait('hurdle');await screenshot('09-栏前收束');
    const full=await state();console.log('Actual trial results',full.history.map(x=>({gear:x.config,measure:x.monitor,success:x.success,meters:x.distance,tilt:x.tilt,slip:x.slip,corrected:x.corrected})));
    await click('查看本班调查记录');assert.equal(await page.locator('#entries li').count(),3);await click('关闭');
    await page.setViewportSize({width:390,height:844});await screenshot('10-手机栏前');
    await click('调查记录');await click('重新开课…');await click('确认重新开课');await wait('intro');await click('▶　播放比赛');
    await page.locator('video').evaluate(v=>v.playbackRate=3);await wait('prediction');
    await click('现在还说不准');await click('揭晓现场　→');await wait('question');await click('翻开现场线索　→');
    await click('观察身体');await screenshot('11-手机线索');assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
    await click('带着猜想去改装　→');await click('激光雷达');await click('用这套装备试跑　→');await wait('result');
    assert(!(await state()).history.at(-1).success);assert(!await button('播放成功过弯　→').count());
    assert.deepEqual(warnings,[]);console.log('PASS browser, pause, cue, hypotheses, failure gating, stored runs, victory, reset, mobile, no page or resource errors');
  }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exit(1)});
